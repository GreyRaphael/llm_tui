package views

import "testing"

func TestIsAutoGeneratedAlias(t *testing.T) {
	tests := []struct {
		name    string
		alias   string
		model   string
		apiType string
		want    bool
	}{
		{"empty alias is not auto-generated", "", "gpt-4o", "openai_chat", false},
		{"empty model never matches", "gpt-4o", "", "openai_chat", false},
		{"bare model", "gpt-4o", "gpt-4o", "openai_chat", true},
		{"legacy model with matching type", "gpt-4o (openai_chat)", "gpt-4o", "openai_chat", true},
		{"legacy suffix for another type", "gpt-4o (anthropic_messages)", "gpt-4o", "openai_chat", false},
		{"custom alias", "DeepSeek Production", "gpt-4o", "openai_chat", false},
		{"custom alias with parentheses", "My (kept) Name", "gpt-4o", "openai_chat", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := isAutoGeneratedAlias(tt.alias, tt.model, tt.apiType); got != tt.want {
				t.Fatalf("isAutoGeneratedAlias(%q, %q, %q) = %v; want %v", tt.alias, tt.model, tt.apiType, got, tt.want)
			}
		})
	}
}
